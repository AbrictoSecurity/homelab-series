#!/usr/bin/env bash
# Script:      logo.sh
# Description: Abricto Security logo banner, source this file from other
#              scripts or run it directly to display the banner.
# Usage:       source "$(dirname "${BASH_SOURCE[0]}")/../lib/logo.sh"
#              or: bash scripts/lib/logo.sh

_PURPLE='\033[0;35m'
_PINK='\033[95m'
_CYAN='\033[1;36m'
_RESET='\033[0m'

echo -e "${_PURPLE}##################################################${_RESET}"
echo -e "${_PURPLE}#######${_CYAN}= .  -  : :  *${_PURPLE}#########${_CYAN}: :  : .. :  *${_PURPLE}######${_RESET}"
echo -e "${_PURPLE}#######             :########*             -######${_RESET}"
echo -e "${_PURPLE}####      ${_CYAN}*######:${_PURPLE}     +###      ${_CYAN}*######${_PURPLE}      *###${_RESET}"
echo -e "${_PURPLE}####+     ${_CYAN}#####${_PURPLE}        ####:     ${_CYAN}#####${_PURPLE}        ####${_RESET}"
echo -e "${_PURPLE}####=     ${_CYAN}###++${_PURPLE}        *###:     ${_CYAN}###++${_PURPLE}        ####${_RESET}"
echo -e "${_PURPLE}####      ${_CYAN}*#   +#.${_PURPLE}     +###      ${_CYAN}*#   =#${_PURPLE}      +###${_RESET}"
echo -e "${_PURPLE}####:     ${_CYAN}##.  +#-${_PURPLE}     *###      ${_CYAN}##   +#:${_PURPLE}     *###${_RESET}"
echo -e "${_PURPLE}####+     ${_CYAN}-:-  ##*${_PURPLE}     ####:     ${_CYAN}::.  ##-${_PURPLE}     ####${_RESET}"
echo -e "${_PURPLE}####         ${_CYAN}####.${_PURPLE}     +###         ${_CYAN}####${_PURPLE}      *###${_RESET}"
echo -e "${_PURPLE}####.     ${_CYAN}#######:${_PURPLE}     +###      ${_CYAN}#######${_PURPLE}      *###${_RESET}"
echo -e "${_PURPLE}#####==.    -  : .  =++#####-+     -    .  *-*####${_RESET}"
echo -e "${_PURPLE}#######             .########*             -######${_RESET}"
echo -e "${_PURPLE}##################################################${_RESET}"
echo -e "${_PINK}#################:     *####     :################${_RESET}"
echo -e "${_PINK}##  #########+                       +#########- #${_RESET}"
echo -e "${_PINK}#  =######=                             :#######  ${_RESET}"
echo -e "${_PINK}#   .=-.                                    -=-   ${_RESET}"
echo -e "${_PINK}##                      =#+                      *${_RESET}"
echo -e "${_PINK}###-                 +#######+                 :##${_RESET}"
echo -e "${_PINK}#######*-.   .=**##################*=.   .-+######${_RESET}"
echo -e "${_PURPLE}##################################################${_RESET}"
echo -e "${_PURPLE}##################################################${_RESET}"
echo -e "${_PURPLE}##################################################${_RESET}"
echo -e "${_PURPLE}##################################################${_RESET}"
echo ""
